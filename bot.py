@router.callback_query(Act.filter())
async def on_callback(cb: CallbackQuery, callback_data: Act) -> None:
    if not cb.from_user:
        return
    u = await ensure_user(cb.from_user.id, cb.from_user.username, cb.from_user.full_name)
    uid = u["user_id"]
    kind, op, idx, sub, val = (
        callback_data.kind,
        callback_data.op,
        callback_data.idx,
        callback_data.sub,
        callback_data.val,
    )

    if kind == "nav":
        if op == "author":
            await edit_or_send(cb, f"ОБ АВТОРЕ ПРОЕКТА\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n{PROJECT_INFO['author']}", inline_home())
        elif op == "history":
            await edit_or_send(cb, f"ИСТОРИЯ ПРОЕКТА\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n{PROJECT_INFO['history']}", inline_home())
        else:
            await set_state_pos(uid, "home", 0)
            await edit_or_send(cb, f"{PROJECT_INFO['title'].upper()}\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n{PROJECT_INFO['about']}", inline_home())
        return

    if kind == "elec":
        await set_state_pos(uid, "elec", idx)
        await edit_or_send(cb, render_elec(idx, fact_mode=(op == "fact")), inline_elec(idx))
        return

    if kind == "rob":
        await set_state_pos(uid, "rob", idx)
        await edit_or_send(cb, render_rob(idx, fact_mode=(op == "fact")), inline_rob(idx))
        return

    if kind == "cmp":
        await set_state_pos(uid, "cmp", idx)
        await edit_or_send(cb, render_cmp(idx, show_all=(op == "all")), inline_cmp(idx))
        return

    if kind == "ai":
        await set_state_pos(uid, "ai", idx)
        await edit_or_send(cb, render_ai(idx), inline_ai(idx))
        return

    if kind == "sec":
        if op == "memo":
            await edit_or_send(cb, SECURITY_MEMO, inline_sec(idx))
        elif op in ("scen",):
            s = SECURITY_SCENARIOS[idx % len(SECURITY_SCENARIOS)]
            await edit_or_send(cb, f"{s['title']}\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n{s['text']}", inline_sec(idx % len(SECURITY_SCENARIOS)))
        elif op == "ans":
            s = SECURITY_SCENARIOS[idx % len(SECURITY_SCENARIOS)]
            ok = (val == 1) == s["is_fraud"]
            verdict = "Верно!" if ok else "Неверно."
            await edit_or_send(cb, f"{s['title']}\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n{verdict}\n\n{s['explanation']}", inline_sec(idx % len(SECURITY_SCENARIOS)))
        return

    if kind == "fact":
        f_idx = random.randrange(len(FACTS)) if op == "random" else idx
        cnt = await add_fact_viewed(uid)
        await set_state_pos(uid, "fact", f_idx)
        await edit_or_send(cb, render_fact(f_idx, cnt), inline_fact(f_idx))
        return

    if kind == "dict":
        await set_state_pos(uid, "dict", idx)
        await edit_or_send(cb, render_dict(idx), inline_dict(idx))
        return

    if kind == "quiz":
        if op == "menu":
            await edit_or_send(cb, "Выберите тест или викторину:", inline_quiz_menu())
            return
        if op == "stats":
            await edit_or_send(cb, await render_stats_text(uid, u["full_name"]), inline_quiz_menu())
            return
        if op in ("start", "randq"):
            sess = start_quiz_session(uid, sub, single=(op == "randq"))
            q = sess["items"][0]
            kb = InlineKeyboardMarkup(
                inline_keyboard=[
                    [InlineKeyboardButton(text=o, callback_data=Act(kind="quiz", op="ans", idx=0, sub=sub, val=i).pack())]
                    for i, o in enumerate(q["opts"])
                ]
                + [[InlineKeyboardButton(text="На главную экспедиции", callback_data=Act(kind="nav", op="home", idx=0).pack())]]
            )
            await edit_or_send(
                cb,
                f"ИГРОВАЯ ЛАБОРАТОРИЯ  /  {q['topic'].upper()}\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\nРАУНД: ВОПРОС 1 ИЗ {len(sess['items'])}  |  ОЧКИ: {sess['score']}\n\n{q['q']}\n\nВыбери один вариант. После ответа откроется разбор.",
                kb,
            )
            return
        if op == "next":
            sess = QUIZ_SESSIONS.get(uid)
            if not sess or idx >= len(sess["items"]):
                await edit_or_send(cb, "Выберите тест:", inline_quiz_menu())
                return
            q = sess["items"][idx]
            kb = InlineKeyboardMarkup(
                inline_keyboard=[
                    [InlineKeyboardButton(text=o, callback_data=Act(kind="quiz", op="ans", idx=idx, sub=sub, val=i).pack())]
                    for i, o in enumerate(q["opts"])
                ]
                + [[InlineKeyboardButton(text="На главную экспедиции", callback_data=Act(kind="nav", op="home", idx=0).pack())]]
            )
            await edit_or_send(
                cb,
                f"ИГРОВАЯ ЛАБОРАТОРИЯ  /  {q['topic'].upper()}\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\nРАУНД: ВОПРОС {idx + 1} ИЗ {len(sess['items'])}  |  ОЧКИ: {sess['score']}\n\n{q['q']}\n\nВыбери один вариант. После ответа откроется разбор.",
                kb,
            )
            return
        if op == "ans":
            sess = QUIZ_SESSIONS.get(uid) or start_quiz_session(uid, sub, single=False)
            items = sess["items"]
            cur_i = min(idx, len(items) - 1)
            q = items[cur_i]
            right_i = int(q["ans"])
            is_ok = val == right_i
            if q["q"] not in sess["done_ids"]:
                sess["done_ids"].add(q["q"])
                if is_ok:
                    sess["score"] += 1
            is_last = cur_i >= len(items) - 1
            verdict = "ТОЧНО В ЦЕЛЬ — +1 БАЛЛ" if is_ok else f"ПОПЫТКА ПРИНЯТА. Правильный ответ: «{q['opts'][right_i]}»."
            tail = ""
            if is_last:
                unlocked = await record_quiz_result(uid, sub, sess["score"], len(items))
                pct = round((sess["score"] / max(1, len(items))) * 100.0, 1)
                ach_txt = ("\nНовые достижения: " + ", ".join(unlocked)) if unlocked else ""
                tail = f"\n\nИтог: {sess['score']}/{len(items)} ({pct}%){ach_txt}"

            nav_rows: list[list[InlineKeyboardButton]] = []
            if not is_last:
                nav_rows.append([InlineKeyboardButton(text="Следующий вопрос", callback_data=Act(kind="quiz", op="next", idx=cur_i + 1, sub=sub).pack())])
            nav_rows.append([
                InlineKeyboardButton(text="Новый раунд", callback_data=Act(kind="quiz", op="start", idx=0, sub=sub).pack()),
                InlineKeyboardButton(text="Мой рейтинг", callback_data=Act(kind="quiz", op="stats", idx=0, sub=sub).pack()),
            ])
            nav_rows.append([InlineKeyboardButton(text="На главную экспедиции", callback_data=Act(kind="nav", op="home", idx=0).pack())])
            await edit_or_send(cb, f"РАЗБОР ОТВЕТА\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\n{verdict}\n\nПОЧЕМУ ЭТО ВАЖНО\n{q['exp']}{tail}", InlineKeyboardMarkup(inline_keyboard=nav_rows))


async def on_error(event: ErrorEvent) -> None:
    logger.exception("Ошибка обработки обновления: %s", event.exception)


async def main() -> None:
    await init_db()
    bot = Bot(token=BOT_TOKEN, default=DefaultBotProperties(parse_mode=None))
    dp = Dispatcher()
    dp.errors.register(on_error)
    dp.include_router(router)

    try:
        await bot.set_my_commands(BOT_COMMANDS)
    except TelegramAPIError as exc:
        logger.warning("Не удалось обновить команды в меню Telegram: %s", exc)

    try:
        await dp.start_polling(bot, allowed_updates=dp.resolve_used_update_types())
    finally:
        await bot.session.close()

 
if __name__ == "__main__":
    try:
        asyncio.run(main())
    except KeyboardInterrupt:
        logger.info("Бот остановлен.")