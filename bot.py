        db.row_factory = aiosqlite.Row
        cur = await db.execute("SELECT * FROM users WHERE user_id = ?", (user_id,))
        row = await cur.fetchone()
        if row is None:
            await db.execute(
                "INSERT INTO users (user_id, username, full_name, last_section, last_idx, facts_viewed, updated_at) "
                "VALUES (?, ?, ?, 'home', 0, 0, ?)",
                (user_id, username, name, ts),
            )
        else:
            await db.execute(
                "UPDATE users SET username = ?, full_name = ?, updated_at = ? WHERE user_id = ?",
                (username, name, ts, user_id),
            )
        await db.commit()
        cur = await db.execute("SELECT * FROM users WHERE user_id = ?", (user_id,))
        row = await cur.fetchone()
        return dict(row)


