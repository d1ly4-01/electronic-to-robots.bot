def start_quiz_session(user_id: int, cat: str, single: bool = False) -> dict[str, Any]:
    pool = QUESTIONS if cat == "all" else [q for q in QUESTIONS if q["cat"] == cat]
    if not pool:
        pool = QUESTIONS
    items = [random.choice(pool)] if single else random.sample(pool, k=min(8, len(pool)))
    sess = {"cat": cat, "items": items, "score": 0, "done_ids": set()}
    QUIZ_SESSIONS[user_id] = sess
    return sess


