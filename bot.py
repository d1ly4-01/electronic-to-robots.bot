async def record_quiz_result(user_id: int, topic: str, score: int, total: int) -> list[str]:
    safe_total = max(1, total)
    acc = round((score / safe_total) * 100.0, 1)
    unlocked: list[str] = []
    async with aiosqlite.connect(DB_PATH) as db:
        await db.execute(
            "INSERT INTO quiz_results (user_id, topic, score, total, accuracy, created_at) VALUES (?, ?, ?, ?, ?, ?)",
            (user_id, topic, score, total, acc, now_utc()),
        )
        await db.commit()
        cur = await db.execute("SELECT COUNT(*) AS c FROM quiz_results WHERE user_id = ?", (user_id,))
        row = await cur.fetchone()
        total_runs = int(row[0]) if row else 1

    if await unlock_achievement(user_id, "first_quiz"):
        unlocked.append(ACHIEVEMENTS["first_quiz"][0])
    if acc >= 80.0 and await unlock_achievement(user_id, "high_accuracy"):
        unlocked.append(ACHIEVEMENTS["high_accuracy"][0])
    if score == total and total > 0 and await unlock_achievement(user_id, "perfect_score"):
        unlocked.append(ACHIEVEMENTS["perfect_score"][0])
    if total_runs >= 5 and await unlock_achievement(user_id, "five_quizzes"):
        unlocked.append(ACHIEVEMENTS["five_quizzes"][0])
    if topic == "security" and await unlock_achievement(user_id, "cyber_guardian"):
        unlocked.append(ACHIEVEMENTS["cyber_guardian"][0])
    return unlocked


async def get_stats(user_id: int) -> dict[str, Any]:
    async with aiosqlite.connect(DB_PATH) as db:
        db.row_factory = aiosqlite.Row
        u_cur = await db.execute("SELECT facts_viewed FROM users WHERE user_id = ?", (user_id,))
        u_row = await u_cur.fetchone()
        facts_viewed = int(u_row["facts_viewed"]) if u_row else 0

        r_cur = await db.execute(
            "SELECT topic, score, total, accuracy, created_at FROM quiz_results WHERE user_id = ? ORDER BY id DESC",
            (user_id,),
        )
        results = [dict(r) for r in await r_cur.fetchall()]

        a_cur = await db.execute(
            "SELECT code, unlocked_at FROM achievements WHERE user_id = ?",
            (user_id,),
        )
        ach_rows = [dict(a) for a in await a_cur.fetchall()]

    return {
        "facts_viewed": facts_viewed,
        "runs": len(results),
        "correct": sum(r["score"] for r in results),
        "questions": sum(r["total"] for r in results),
        "best_acc": max((r["accuracy"] for r in results), default=0.0),
        "recent": results[:5],
        "achievements": ach_rows,
    }


