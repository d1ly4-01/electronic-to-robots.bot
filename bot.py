    if not msg.from_user:
        return
    u = await ensure_user(msg.from_user.id, msg.from_user.username, msg.from_user.full_name)
    cmd = (msg.text or "").split()[0].lstrip("/").lower()
    sec = u["last_section"]
    idx = int(u["last_idx"])
    if cmd == "restart":
        new_idx = 0
    elif cmd == "next":
        new_idx = idx + 1
    else:
        new_idx = max(0, idx - 1)
    await set_state_pos(u["user_id"], sec, new_idx)

    if sec == "elec":
        await msg.answer(render_elec(new_idx), reply_markup=inline_elec(new_idx))
    elif sec == "rob":
        await msg.answer(render_rob(new_idx), reply_markup=inline_rob(new_idx))
    elif sec == "cmp":
        await msg.answer(render_cmp(new_idx), reply_markup=inline_cmp(new_idx))
    elif sec == "ai":
        await msg.answer(render_ai(new_idx), reply_markup=inline_ai(new_idx))
    elif sec == "dict":
        await msg.answer(render_dict(new_idx), reply_markup=inline_dict(new_idx))
    elif sec == "fact":
        cnt = await add_fact_viewed(u["user_id"])
        await msg.answer(render_fact(new_idx, cnt), reply_markup=inline_fact(new_idx))
